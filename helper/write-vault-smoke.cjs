const fs = require('node:fs/promises');
const path = require('node:path');
const { constants } = require('node:fs');
(async () => {
  const root = path.resolve(__dirname, '..');
  const config = JSON.parse(await fs.readFile(path.join(root, '.local/export-config.json'), 'utf8'));
  const output = path.resolve(config.output), vault = path.resolve(config.vault);
  const relative = path.relative(vault, output);
  if (relative.startsWith('..') || path.isAbsolute(relative)) throw new Error('测试目录不在仓库内');
  await fs.access(path.join(vault, '.obsidian'));
  const attachments = path.join(output, 'Bili-Peek附件'); await fs.mkdir(attachments, { recursive: true });
  const realVault = await fs.realpath(vault), realOutput = await fs.realpath(attachments);
  const realRelative = path.relative(realVault, realOutput);
  if (realRelative.startsWith('..') || path.isAbsolute(realRelative)) throw new Error('测试目录链接指向仓库外');
  const video = path.join(attachments, 'Bili-Peek-保存验收.mp4');
  await fs.copyFile(path.join(root, '.local/live-sample.mp4'), video, constants.COPYFILE_EXCL);
  const note = path.join(output, 'Bili-Peek 保存验收.md');
  await fs.writeFile(note, `---\ntags: [工具验证]\ncategory: 保存验收\nsource: "https://www.bilibili.com/video/BV12N4y1M7rh/"\nstart_seconds: 10\nend_seconds: 15\nactual_duration: 5.021334\nsubtitle_status: 登录后才能取得\n---\n\n# Bili-Peek 保存验收\n\n![[Bili-Peek附件/Bili-Peek-保存验收.mp4]]\n\n这是公开 B 站视频第 1 P 的 00:10–00:15 测试片段，用于检查本地视频附件和笔记写入。视频与声音已验证，实际时长 5.021334 秒。\n\n## 字幕状态\n\n真实 B 站字幕接口要求登录，本次未获取字幕。这条笔记只验证媒体和仓库写入，不代表视频加字幕完整导出已通过。正式保存时，字幕缺失会提示失败，不会伪造原文。\n`, { encoding: 'utf8', flag: 'wx' });
  await fs.access(note); await fs.access(video); console.log('PASS: 新验收笔记与视频附件已写入：' + note);
})().catch(error => { console.error(error.code || error.message); process.exitCode = 1; });
